def build_suspected_confirm_prompt(pet_name: str, symptoms: str,
                                   answers: list[str]) -> str:
    ans = "\n\n".join(f"- {a}" for a in (answers or []) if a) or "(검색 결과 없음 — 질환은 빈 배열로)"
