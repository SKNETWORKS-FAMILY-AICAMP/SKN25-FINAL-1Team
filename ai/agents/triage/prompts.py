# ───────────────────────── 완료: 의심질환 안내 + 예약 확인 ─────────────────────────
_DISCLAIMER = (
    "다만 이건 **확정 진단이 아니라 참고**로만 살짝 봐주세요. 정확한 건 "
    "수의사 선생님이 직접 살펴봐 주시는 게 가장 안심돼요."
)


def build_suspected_confirm_message(
    pet_name: str,
    rag_diseases: list[str],
    final_urgency: str = "GREEN",
    urgency_tier: str = "normal",
    safety_noted: bool = False,
) -> str:
    """RAG 유사사례 기반 의심질환 안내 + 강한 디스클레이머 + 예약 확인 멘트."""
    name = pet_name or "아이"
    diseases = list(dict.fromkeys(d for d in (rag_diseases or []) if d))[:3]
    if diseases:
        dz = " · ".join(diseases)
        head = (f"보내주신 증상만으로는 **{dz}** 같은 가능성을 참고해볼 수 있어요. "
                f"{_DISCLAIMER}")
    else:
        head = (f"{name}의 증상은 잘 확인했어요. {_DISCLAIMER}")
    urgency = (final_urgency or "GREEN").upper()
    tier = (urgency_tier or "normal").lower()
    if safety_noted or urgency in ("RED", "ORANGE") or tier == "critical":
        booking = (
            "가능하면 빠르게 진료를 받아보시는 게 좋아요. "
            "원하시면 가장 빠른 예약도 확인해드릴게요."
        )
    elif urgency == "YELLOW" or tier == "high":
        booking = (
            "한 번 진료로 확인해보시는 게 좋겠어요. "
            "원하시면 예약도 도와드릴게요."
        )
    else:
        booking = "원하시면 예약도 도와드릴게요."
    return f"{head}\n\n{booking}"


# 의심질환 = RAG 검색 결과(수의사 답변)에서 '실제로 적힌 질환'만. 꾸며내지 않는다.
#  검색은 top-k를 그냥 가져오고(threshold 컷 X), LLM이 증상에 맞는 것만 골라(리랭크) 질환을 추린다.
_SUSPECT_GEN_SYSTEM = _TONE + """

너는 동물병원 문진 도우미야. {pet_name}의 증상 문진을 막 마쳤어.

[{pet_name}의 증상(보호자가 말한 것)]
{symptoms}

[내부 진료 우선도 컨텍스트 — 보호자에게 값이나 등급명을 그대로 말하지 마]
- final_urgency: {final_urgency}
- urgency_tier: {urgency_tier}
- safety_noted: {safety_noted}

[검색된 비슷한 사례의 수의사 답변들 — 이 중 증상과 '맞는 것만' 고르고, 동떨어진 건 버려]
{answers}

할 일:
1) 위 '수의사 답변'에 실제로 적힌 질환 중, {pet_name}의 증상과 맞는 것을 골라 suspected_diseases(한국어)에 담아라.
   - 답변에 없는 질환을 절대 지어내지 마라. 증상과 맞는 게 없으면 빈 배열([]).
2) message = 문진을 마치며 보낼 '따뜻한 마무리 메시지'. 아래 흐름을 자연스럽게 따라라(매번 다른 표현, 딱딱한 틀 X):
   ① 지금까지 들은 내용을 '상황 한 문장'으로 해석해서 말해라 — 증상을 나열·재배열하지 말고, '무엇이 문제인 상황인지'로 묶어라.
      · 나쁨(나열): "목이 붓고 아프고 씹기 불편해 보여서…"  →  좋음(해석): "목 주변 통증 때문에 씹는 것도 불편해 보이는 상황이네요."
      · 나쁨(나열): "눈물이 있고 발바닥이 벗겨졌고…"        →  좋음(해석): "눈과 발바닥 모두 확인이 필요한 상황으로 보여요."
   ② 보호자의 걱정, 증상 지속·악화, 뚜렷한 불편, 수술 후 변화가 실제 대화에 명확할 때만 짧게 한 번 공감해도 된다.
      모든 메시지에 공감을 강제로 넣거나, 보호자가 말하지 않은 감정을 지어내지 마라.
   ③ 단정 진단은 피해라 — suspected가 있어도 "~일 수 있어요/가능성도 있어요" 정도로만, 병명 확정은 금지.
   ④ 참고용임을 부드럽게: "보내주신 증상만으로는 특정 질환을 단정하긴 어렵다", "지금 안내는 참고용으로만 봐주세요" 톤.
      ★ suspected가 비어 있어도 "질환이 안 보인다/딱 맞는 게 없다"는 식으로 말하지 마라(불안하게 들린다) —
        "현재 말씀만으로는 특정 질환으로 단정하긴 어렵다"처럼 자연스럽게.
   ⑤ 내부 진료 우선도 컨텍스트를 참고해 '진료 필요성/우선도 → 예약 지원' 순서로 예약 권유 강도를 조절해라.
      예약 CTA가 의료적 필요성보다 먼저 나오면 안 된다.
      - final_urgency가 GREEN이고 urgency_tier가 normal이며 safety_noted가 false인 경우:
        선택권 중심으로 가볍게 제안한다. 불필요하게 "바로"를 붙이지 마라.
        예: "원하시면 예약도 도와드릴게요."
      - final_urgency가 YELLOW이거나 urgency_tier가 high인 경우:
        한 번 진료로 확인해보는 게 좋다는 권고를 먼저 말하고 예약 지원을 제안한다.
        예: "한 번 진료로 확인해보시는 게 좋겠어요. 원하시면 예약도 도와드릴게요."
      - final_urgency가 ORANGE/RED이거나 urgency_tier가 critical이거나 safety_noted가 true인 경우:
        가능한 빠른 진료 필요성을 먼저 말하고, 그 다음 가장 빠른 예약 확인을 제안한다.
        safety_noted가 true면 앞에서 빠른 진료 안내가 이미 보였다는 뜻이다. 같은 문장을 기계적으로 반복할 필요는 없지만,
        마지막을 일반적인 "한 번 진료/예약" 수준으로 낮추지 말고 "가장 빠른 예약" 지원까지 같은 우선도로 이어라.
        예: "가능하면 빠르게 진료를 받아보시는 게 좋아요. 원하시면 가장 빠른 예약도 확인해드릴게요."
      - ★ 진료 필요성의 강도와 마지막 예약 CTA의 강도는 반드시 일치해야 한다.
        safety_noted가 true이거나 본문에서 "지금 바로/되도록 빨리/가능하면 빠르게 진료"를 안내했다면,
        마지막을 일반적인 "예약도 도와드릴게요"로 낮추는 것은 금지한다.
        반드시 "가장 빠른 예약을 확인해드릴게요" 또는 "가장 빠른 시간대부터 찾아드릴게요"처럼 이어라.
        단, 자동으로 예약하거나 확정한 것처럼 말하지 말고 "확인/찾기" 수준으로만 제안한다.
      - 신호가 충돌하면 더 안전한 쪽으로 표현하되, "큰일", "매우 위험"처럼 과도하게 겁주는 말은 피한다.
      - final_urgency, urgency_tier, safety_noted 및 RED/YELLOW/GREEN/ORANGE 같은 내부 값·등급명은 보호자에게 절대 노출하지 마라.
   - 출력 전 마지막 두 문장을 스스로 확인해라:
     빠른 진료를 권했다면 CTA도 가장 빠른 예약/시간대 확인인가? 아니라면 같은 우선도로 고쳐서 출력해라.
   - ⛔ 내부 표현 금지: "검색된 사례", "검색 결과", "비슷한 사례에서는", "데이터베이스", "RAG",
     "딱 맞는 질환이 보인다/안 보인다" 등 시스템 내부(검색·질환매칭)가 드러나는 말로 시작·서술하지 마라.
   - ★ 읽기 쉽게 줄바꿈(\\n\\n)으로 2~3 덩어리로 나눠라. 한 문단으로 길게 이어 쓰지 마.
     예) (상황 한 문장 해석 + 단정 어려움)\\n\\n(참고용·수의사 확인 권유)\\n\\n(예약 권유 한 문장)

JSON으로만 답해:
{{"suspected_diseases":["한국어 질환명"], "message":"여러 줄(\\n\\n)로 나눈 메시지 본문"}}"""


def build_suspected_confirm_prompt(
    pet_name: str,
    symptoms: str,
    answers: list[str],
    final_urgency: str = "GREEN",
    urgency_tier: str = "normal",
    safety_noted: bool = False,
) -> str:
    ans = "\n\n".join(f"- {a}" for a in (answers or []) if a) or "(검색 결과 없음 — 질환은 빈 배열로)"
    return _SUSPECT_GEN_SYSTEM.format(
        pet_name=pet_name or "아이",
        symptoms=(symptoms or "").strip() or "(증상 정보 부족)",
        answers=ans,
        final_urgency=(final_urgency or "GREEN").upper(),
        urgency_tier=(urgency_tier or "normal").lower(),
        safety_noted=str(bool(safety_noted)).lower(),
    )


