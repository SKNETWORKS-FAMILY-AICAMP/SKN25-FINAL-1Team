def _covered_topics(section_id: str | None, extracted: dict | None) -> str:
    """이미 추출된(=이미 물어 답을 얻은) 항목의 '개념'을 자연어 토픽으로 — 질문 콜이 다시 안 묻게.

    변수명/enum값(스키마)은 노출하지 않는다(대본 느낌 방지). '무엇을 이미 물었나'(토픽)만 알려준다.
    """
    if not section_id or not extracted:
        return "(아직 없음 — 가장 걱정되는 것부터 편하게 들어봐)"
    vals = (extracted or {}).get(section_id) or {}
    if not vals:
        return "(아직 없음)"
    schema = engine.variables_for(section_id)
    topics: list[str] = []
    for k in vals:
        concept = (schema.get(k) or {}).get("concept", k)
        topic = concept.split("(")[0].strip()   # '기침(없음/가끔/...)' → '기침'
        if topic and topic not in topics:
            topics.append(topic)
    return ", ".join(topics) if topics else "(아직 없음)"


